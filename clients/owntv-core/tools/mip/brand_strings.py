#!/usr/bin/env python3
"""miptv (operator edition): generates the resource overrides that take the YAiPlayer name, GitHub and Telegram out
of every visible text, in EVERY language. Run it before building with -Powntv.mip=true (the mip.yml workflow does);
the result (src/mip/res of each app) is added to the `standard` flavour only for that build, so YAiPlayer is unchanged.
Nothing is edited by hand: a new string added to the shared core is picked up by the next run.
"""
import re
import shutil
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
CLIENTS = Path(__file__).resolve().parents[3]
SOURCES = [CLIENTS / "owntv-core/core/src/main/res", CLIENTS / "android-tv/app/src/main/res", CLIENTS / "android-mobile/app/src/main/res", CLIENTS / "android-tv/app/src/radio/res", CLIENTS / "android-mobile/app/src/radio/res"]
TARGETS = [CLIENTS / "android-tv/app/src/mip/res", CLIENTS / "android-mobile/app/src/mip/res"]
NAME = "miptv"
HEADER = ('<?xml version="1.0" encoding="utf-8"?>\n<!-- GENERATED by tools/mip/brand_strings.py - do not edit. -->\n'
          '<resources xmlns:xliff="urn:oasis:names:tc:xliff:document:1.2" xmlns:tools="http://schemas.android.com/tools">\n')
ELEMENT = re.compile(r'<(string|plurals|string-array)\s+name="([^"]+)"([^>]*)>(.*?)</\1>', re.S)
BRAND = re.compile(r'YAi ?Play\w*|GitHub(?: Releases)?|Telegram|t\.me/\S+|GPL', re.I)
CHECK = re.compile(r'YAi ?Play|GitHub|Telegram|t\.me/|GPL', re.I)


def neutral(text: str) -> str:
    return BRAND.sub(NAME, text)


def main() -> int:
    per_dir: dict[str, dict[str, str]] = {}
    for root in SOURCES:
        for values in sorted(root.glob("values*")):
            for f in sorted(values.glob("*.xml")):
                if f.name in ("strings_mip.xml", "strings_mip_brand.xml"):
                    continue
                text = f.read_text(encoding="utf-8")
                for kind, name, attrs, body in ELEMENT.findall(text):
                    if name == "app_name" or not CHECK.search(body):
                        continue
                    new = neutral(body)
                    if new != body:
                        per_dir.setdefault(values.name, {})[name] = f'    <{kind} name="{name}"{attrs}>{new}</{kind}>\n'
    for target in TARGETS:
        if target.exists():
            shutil.rmtree(target)
        base = per_dir.setdefault("values", {})
        base["app_name"] = f'    <string name="app_name" translatable="false">{NAME}</string>\n'
        for values, items in per_dir.items():
            out = target / values
            out.mkdir(parents=True, exist_ok=True)
            (out / "strings_mip_brand.xml").write_text(HEADER + "".join(items.values()) + "</resources>\n", encoding="utf-8")
        # the splash screen: the miptv mark (transparent, inside the middle third so the round system mask never cuts it;
        # drawn by tools/mip/make_brand.py) instead of the YAi mark
        icon = HERE / "assets/mip_splash.png"
        if icon.exists():
            (target / "drawable").mkdir(parents=True, exist_ok=True)
            shutil.copy(icon, target / "drawable/yai_splash_icon.png")
    print("miptv brand overrides:", {k: len(v) for k, v in per_dir.items() if len(v) > 0 and k in ("values", "values-ru", "values-uk")}, "dirs:", len(per_dir))
    return 0


if __name__ == "__main__":
    sys.exit(main())
