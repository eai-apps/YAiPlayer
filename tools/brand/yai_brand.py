#!/usr/bin/env python3
"""Regenerates every brand image of the YAiPlayer apps from a few constants (name, colours).

Run from the repository root:  python3 tools/brand/yai_brand.py
For another product (white-label), change BRAND_NAME / VARIANTS below and run it again.
Writes into clients/owntv-core/core/src/main/res (icons, marks, banners, monochrome).
"""
import math, os
from PIL import Image, ImageDraw, ImageFont

BRAND_NAME = "YAiPlayer"
DOT = "#22D3EE"          # the small "signal" dot
# variant name -> (background, triangle colour, dot colour)
VARIANTS = {
    "eggshell":    ("#5B3FD6", "#FFFFFF", DOT),       # default launcher icon: violet
    "petrol":      ("#0E7C86", "#FFFFFF", "#FDE68A"),
    "sunflower":   ("#E5A50A", "#FFFFFF", "#5B3FD6"),
    "cobalt":      ("#3E63D2", "#FFFFFF", DOT),
    "tomato":      ("#D8523C", "#FFFFFF", "#FDE68A"),
    "board":       ("#171A24", "#FFFFFF", DOT),
    "olive":       ("#2F8F5B", "#FFFFFF", "#FDE68A"),
    "olive_cream": ("#E8E2FF", "#5B3FD6", "#0E7C86"),
    "pixel":       ("#0F172A", "#FFFFFF", DOT),
}
RES = os.path.join(os.path.dirname(__file__), "..", "..", "clients", "owntv-core", "core", "src", "main", "res")
TRI = [(22.7, 20.0), (40.2, 30.0), (22.7, 40.0)]   # in the 56 x 56 mark; same place as owntv_mark_play


def hexa(c):
    c = c.lstrip("#")
    return "#FF" + c.upper()


def write(path, text):
    full = os.path.join(RES, path)
    os.makedirs(os.path.dirname(full), exist_ok=True)
    with open(full, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def mark_xml(size_dp, bg, tri, dot, small):
    r = 13
    dot_xml = "" if small else (
        f'<path android:pathData="M44,14m-3.2,0a3.2,3.2 0 1,0 6.4,0a3.2,3.2 0 1,0 -6.4,0" android:fillColor="{hexa(dot)}"/>')
    t = " ".join(f"{x},{y}" for x, y in TRI)
    tri_path = f"M{TRI[0][0]},{TRI[0][1]}L{TRI[1][0]},{TRI[1][1]}L{TRI[2][0]},{TRI[2][1]}Z"
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/brand/yai_brand.py. Do not edit by hand. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{size_dp}dp" android:height="{size_dp}dp"
    android:viewportWidth="56" android:viewportHeight="56">
    <path android:pathData="M{r},0H{56-r}A{r},{r} 0 0 1 56,{r}V{56-r}A{r},{r} 0 0 1 {56-r},56H{r}A{r},{r} 0 0 1 0,{56-r}V{r}A{r},{r} 0 0 1 {r},0Z" android:fillColor="{hexa(bg)}"/>
    <path android:pathData="{tri_path}" android:fillColor="{hexa(tri)}" android:strokeColor="{hexa(tri)}" android:strokeWidth="4.6" android:strokeLineJoin="round"/>
    {dot_xml}
</vector>
'''


def rounded_tri(draw, pts, r, fill, s):
    pts = [(x * s, y * s) for x, y in pts]
    r *= s
    draw.polygon(pts, fill=fill)
    for (x, y) in pts:
        draw.ellipse([x - r, y - r, x + r, y + r], fill=fill)
    for i in range(3):
        (x1, y1), (x2, y2) = pts[i], pts[(i + 1) % 3]
        dx, dy = x2 - x1, y2 - y1
        n = math.hypot(dx, dy)
        nx, ny = -dy / n * r, dx / n * r
        draw.polygon([(x1 + nx, y1 + ny), (x2 + nx, y2 + ny), (x2 - nx, y2 - ny), (x1 - nx, y1 - ny)], fill=fill)


def foreground_png(px, tri, dot):
    s = 4
    big = px * s
    img = Image.new("RGBA", (big, big), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    # 108 dp canvas, safe zone 66 dp: triangle about 34 dp wide, optically centred
    k = px / 108.0
    pts = [(38 * k, 34 * k), (74 * k, 54 * k), (38 * k, 74 * k)]
    rounded_tri(d, pts, 3.2 * k, tri, s)
    cx, cy, rr = 76 * k * s, 32 * k * s, 4.5 * k * s
    d.ellipse([cx - rr, cy - rr, cx + rr, cy + rr], fill=dot)
    return img.resize((px, px), Image.LANCZOS)


def banner_png(bg, tri, dot):
    w, h, s = 320, 180, 3
    img = Image.new("RGBA", (w * s, h * s), bg)
    d = ImageDraw.Draw(img)
    k = 2.4
    ox, oy = -30, 18          # puts the triangle (from the 56 x 56 mark) left of the name, vertically centred
    pts = [(ox + x * k, oy + (y - 30) * k + 72) for x, y in TRI]
    rounded_tri(d, pts, 1.9 * k, tri, s)
    cx, cy, rr = (ox + 46 * k) * s, (oy + (14 - 30) * k + 72) * s, 1.4 * k * s
    d.ellipse([cx - rr, cy - rr, cx + rr, cy + rr], fill=dot)
    font = None
    for p in ("/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf",
              "/usr/share/fonts/truetype/liberation/LiberationSans-Bold.ttf"):
        if os.path.exists(p):
            font = ImageFont.truetype(p, 40 * s)
            break
    if font:
        d.text((96 * s, 66 * s), BRAND_NAME, font=font, fill=tri)
    return img.resize((w, h), Image.LANCZOS)


def main():
    colors = ['<?xml version="1.0" encoding="utf-8"?>',
              "<!-- Generated by tools/brand/yai_brand.py. Do not edit by hand. -->", "<resources>"]
    for name, (bg, tri, dot) in VARIANTS.items():
        if name != "pixel":   # pixel's colour lives in owntv_icon_colors_stage.xml
            colors.append(f'    <color name="owntv_icon_bg_{name}">{bg}</color>')
        write(f"drawable/owntv_mark_{name}.xml", mark_xml(56, bg, tri, dot, False))
        write(f"drawable/owntv_mark_small_{name}.xml", mark_xml(32, bg, tri, dot, True))
        for dens, px in (("mdpi", 108), ("hdpi", 162), ("xhdpi", 216), ("xxhdpi", 324), ("xxxhdpi", 432)):
            p = os.path.join(RES, f"mipmap-{dens}", f"owntv_icon_{name}_foreground.png")
            os.makedirs(os.path.dirname(p), exist_ok=True)
            foreground_png(px, tri, dot).save(p)
        banner = banner_png(bg, tri, dot).convert("RGB")
        for dens in ("mdpi", "hdpi", "xhdpi", "xxhdpi", "xxxhdpi"):
            bp = os.path.join(RES, f"drawable-{dens}", f"owntv_banner_{name}.png")
            if os.path.exists(bp):
                keep = Image.open(bp).size           # the TV banner keeps the size it already had
                banner.resize(keep, Image.LANCZOS).save(bp)
    colors.append("</resources>")
    write("values/owntv_icon_colors_stage.xml", '''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/brand/yai_brand.py. Do not edit by hand. -->
<resources>
    <color name="owntv_icon_bg_pixel">%s</color>
</resources>
''' % VARIANTS["pixel"][0])
    write("values/owntv_icon_colors.xml", "\n".join(colors) + "\n")
    # monochrome (themed icon): the triangle only
    write("drawable/owntv_icon_monochrome.xml", '''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/brand/yai_brand.py. Do not edit by hand. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp"
    android:viewportWidth="108" android:viewportHeight="108">
    <path android:pathData="M38,34L74,54L38,74Z" android:fillColor="#FFFFFFFF" android:strokeColor="#FFFFFFFF" android:strokeWidth="6.4" android:strokeLineJoin="round"/>
</vector>
''')


if __name__ == "__main__":
    main()
